// Command gen-config-schema writes the JSON Schema for the Themis
// configuration file and the custom resource definitions, generated from the
// Go types in internal/config.
package main

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"slices"
	"strings"

	"github.com/invopop/jsonschema"
	"sigs.k8s.io/yaml"

	"github.com/hzerrad/themis/internal/config"
)

func main() {
	if len(os.Args) != 3 {
		fmt.Fprintln(os.Stderr, "usage: gen-config-schema <output.json> <crd-directory>")
		os.Exit(2)
	}
	if err := run(os.Args[1], os.Args[2]); err != nil {
		fmt.Fprintln(os.Stderr, "gen-config-schema:", err)
		os.Exit(1)
	}
}

func run(out, crds string) error {
	r := &jsonschema.Reflector{
		// Every field is required unless its JSON tag says omitempty.
		RequiredFromJSONSchemaTags: false,
		DoNotReference:             true,
	}
	if err := r.AddGoComments("github.com/hzerrad/themis", "./internal/config"); err != nil {
		return fmt.Errorf("read doc comments: %w", err)
	}
	s := r.Reflect(&config.Config{})

	// The kind syntax lives in Go; copy it in rather than repeating it in a
	// struct tag.
	kinds := s.Properties.Value("profiles").Items.Properties.Value("match").Properties.Value("targetKinds").Items
	kinds.Pattern = config.TargetKindPattern
	if err := writeCRDs(r, crds); err != nil {
		return err
	}
	s.ID = "https://github.com/hzerrad/themis/deploy/config/themis.schema.json"
	s.Title = "Themis configuration"

	data, err := json.MarshalIndent(s, "", "  ")
	if err != nil {
		return err
	}
	return os.WriteFile(out, append(data, '\n'), 0o644) //nolint:gosec // a public schema committed to the repo
}

// writeCRDs writes the custom resource definitions, with specs from the same
// Go types as the configuration file.
func writeCRDs(r *jsonschema.Reflector, dir string) error {
	profile, err := structural(r.Reflect(&config.Profile{}))
	if err != nil {
		return err
	}
	// The resource's metadata.name is the profile's name.
	delete(profile["properties"].(map[string]any), "name")                                                        //nolint:forcetypeassert // an object schema
	profile["required"] = slices.DeleteFunc(profile["required"].([]any), func(v any) bool { return v == "name" }) //nolint:forcetypeassert // the field is required
	settings, err := structural(r.Reflect(&config.ThemisConfigSpec{}))
	if err != nil {
		return err
	}
	for _, c := range []struct {
		file, kind, plural, scope string
		spec                      map[string]any
		rules                     []any
	}{
		{"incidentprofiles.yaml", "IncidentProfile", "incidentprofiles", "Namespaced", profile, nil},
		{"themisconfigs.yaml", "ThemisConfig", "themisconfigs", "Cluster", settings, []any{map[string]any{
			"rule":    "self.metadata.name == 'themis'",
			"message": "there is one ThemisConfig per cluster, and it must be named themis",
		}}},
	} {
		data, err := yaml.Marshal(crd(c.kind, c.plural, c.scope, c.spec, c.rules))
		if err != nil {
			return err
		}
		header := "# Generated by scripts/gen-config-schema from internal/config. Do not edit.\n"
		if err := os.WriteFile(filepath.Join(dir, c.file), append([]byte(header), data...), 0o644); err != nil { //nolint:gosec // a public manifest committed to the repo
			return err
		}
	}
	return nil
}

func crd(kind, plural, scope string, spec map[string]any, rules []any) map[string]any {
	root := map[string]any{
		"type": "object",
		"properties": map[string]any{
			"spec": spec,
			"status": map[string]any{
				"type": "object",
				"properties": map[string]any{
					"digest": map[string]any{"type": "string"},
					"conditions": map[string]any{
						"type":                       "array",
						"x-kubernetes-list-type":     "map",
						"x-kubernetes-list-map-keys": []any{"type"},
						"items": map[string]any{
							"type":                                 "object",
							"x-kubernetes-preserve-unknown-fields": true,
							"required":                             []any{"type", "status"},
							"properties": map[string]any{
								"type":   map[string]any{"type": "string"},
								"status": map[string]any{"type": "string"},
							},
						},
					},
				},
			},
		},
		"required": []any{"spec"},
	}
	if rules != nil {
		root["x-kubernetes-validations"] = rules
	}
	return map[string]any{
		"apiVersion": "apiextensions.k8s.io/v1",
		"kind":       "CustomResourceDefinition",
		"metadata":   map[string]any{"name": plural + ".themis.dev"},
		"spec": map[string]any{
			"group": "themis.dev",
			"scope": scope,
			"names": map[string]any{"kind": kind, "listKind": kind + "List", "plural": plural, "singular": strings.ToLower(kind)},
			"versions": []any{map[string]any{
				"name": "v1alpha1", "served": true, "storage": true,
				"subresources": map[string]any{"status": map[string]any{}},
				"additionalPrinterColumns": []any{
					map[string]any{"name": "Accepted", "type": "string", "jsonPath": `.status.conditions[?(@.type=="Accepted")].status`},
					map[string]any{"name": "Reason", "type": "string", "jsonPath": `.status.conditions[?(@.type=="Accepted")].reason`},
				},
				"schema": map[string]any{"openAPIV3Schema": root},
			}},
		},
	}
}

// structural turns a JSON Schema into what Kubernetes accepts: no $schema, no
// uniqueItems, and no additionalProperties alongside properties.
func structural(s *jsonschema.Schema) (map[string]any, error) {
	data, err := json.Marshal(s)
	if err != nil {
		return nil, err
	}
	var out map[string]any
	if err := json.Unmarshal(data, &out); err != nil {
		return nil, err
	}
	clean(out)
	return out, nil
}

func clean(node map[string]any) {
	for _, drop := range []string{"$schema", "$id", "uniqueItems"} {
		delete(node, drop)
	}
	if v, ok := node["additionalProperties"].(bool); ok && !v {
		delete(node, "additionalProperties")
	}
	for _, v := range node {
		switch c := v.(type) {
		case map[string]any:
			clean(c)
		case []any:
			for _, item := range c {
				if m, ok := item.(map[string]any); ok {
					clean(m)
				}
			}
		}
	}
}
