// Command gen-alert-rules writes the alerting rules Themis ships into the Helm
// chart, which installs them as a PrometheusRule, and into the kind cluster's
// monitoring values, faster, as the overrides file says.
package main

import (
	"errors"
	"fmt"
	"os"
	"slices"
	"strings"

	"sigs.k8s.io/yaml"

	"github.com/hzerrad/themis/internal/incident/intake/rules"
)

func main() {
	if len(os.Args) != 4 {
		fmt.Fprintln(os.Stderr, "usage: gen-alert-rules <chart-rules.yaml> <dev-overrides.yaml> <dev-values.yaml>")
		os.Exit(2)
	}
	if err := run(os.Args[1], os.Args[2], os.Args[3]); err != nil {
		fmt.Fprintln(os.Stderr, "gen-alert-rules:", err)
		os.Exit(1)
	}
}

// override is how the kind cluster's rule for one alert differs.
type override struct {
	For     string            `json:"for"`
	Windows map[string]string `json:"windows"`
	Expr    string            `json:"expr"`
}

func run(chart, overridesFile, devValues string) error {
	if err := os.WriteFile(chart, rules.File, 0o644); err != nil { //nolint:gosec // a file in the repository
		return err
	}
	shipped, err := rules.Shipped()
	if err != nil {
		return err
	}
	b, err := os.ReadFile(overridesFile) //nolint:gosec // a file in the repository
	if err != nil {
		return err
	}
	var overrides map[string]override
	if err := yaml.UnmarshalStrict(b, &overrides); err != nil {
		return fmt.Errorf("%s: %w", overridesFile, err)
	}
	var errs []error
	seen := map[string]bool{}
	for g := range shipped.Groups {
		for r := range shipped.Groups[g].Rules {
			rule := &shipped.Groups[g].Rules[r]
			o, ok := overrides[rule.Alert]
			if !ok {
				continue
			}
			seen[rule.Alert] = true
			if o.For != "" {
				rule.For = o.For
			}
			for from, to := range o.Windows {
				if !strings.Contains(rule.Expr, "["+from+"]") {
					errs = append(errs, fmt.Errorf("%s: %s has no [%s] window", overridesFile, rule.Alert, from))
				}
				rule.Expr = strings.ReplaceAll(rule.Expr, "["+from+"]", "["+to+"]")
			}
			if o.Expr != "" {
				rule.Expr = o.Expr
			}
		}
	}
	for name := range overrides {
		if !seen[name] {
			errs = append(errs, fmt.Errorf("%s: Themis ships no rule for %s", overridesFile, name))
		}
	}
	if len(errs) > 0 {
		slices.SortFunc(errs, func(a, b error) int { return strings.Compare(a.Error(), b.Error()) })
		return errors.Join(errs...)
	}
	out, err := yaml.Marshal(map[string]any{"serverFiles": map[string]any{"alerting_rules.yml": shipped}})
	if err != nil {
		return err
	}
	header := "# Generated by make gen from internal/incident/intake/rules/rules.yaml and\n" +
		"# scripts/dev/monitoring/fast.yaml: edit those. The alerting rules make\n" +
		"# monitoring-up installs on kind.\n"
	return os.WriteFile(devValues, append([]byte(header), out...), 0o644) //nolint:gosec // a file in the repository
}
