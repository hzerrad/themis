// Command gen-fix-list writes the names of the fixes Themis has into the Helm
// chart, which lets HolmesGPT suggest each of them unless holmesgpt.fixes
// names fewer.
package main

import (
	"fmt"
	"maps"
	"os"
	"slices"

	"sigs.k8s.io/yaml"

	"github.com/hzerrad/themis/internal/catalog"
)

const header = "# Generated by make gen from the fixes Themis has: don't edit. HolmesGPT may\n" +
	"# suggest each of them unless holmesgpt.fixes names fewer.\n"

func main() {
	if len(os.Args) != 2 {
		fmt.Fprintln(os.Stderr, "usage: gen-fix-list <chart-fixes.yaml>")
		os.Exit(2)
	}
	out, err := yaml.Marshal(slices.Sorted(maps.Keys(catalog.Fixes())))
	if err == nil {
		err = os.WriteFile(os.Args[1], append([]byte(header), out...), 0o644) //nolint:gosec // a file in the repository
	}
	if err != nil {
		fmt.Fprintln(os.Stderr, "gen-fix-list:", err)
		os.Exit(1)
	}
}
